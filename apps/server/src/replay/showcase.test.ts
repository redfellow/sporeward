import {it,expect} from 'vitest';
import {matchContacts} from '@sporeward/game';
import {loadTampereAccess} from '../spatial/tampere';
import {publicAccess} from '../spatial/access';
import {renderShowcase} from './showcase';
it('covers every guide state and both personal overlays with deterministic valid world data',async()=>{
 const a=await renderShowcase(1800000000000),b=await renderShowcase(1800000000000);
 expect(a).toEqual(b);
 expect(a.renderTest!.examples.map(e=>e.name)).toEqual(['Light effort','Medium effort','Heavy effort','Disintegrating','Remnants','Withering','Clearing','Cracks forming','Splitting','On cooldown','Visited this outing','Cleared · protection']);
 const named=(name:string)=>a.outbreaks.find(o=>o.name===name)!;
 expect(named('Light effort').visitsRemaining).toBeLessThan(named('Medium effort').visitsRemaining);
 expect(named('Medium effort').visitsRemaining).toBeLessThan(named('Heavy effort').visitsRemaining);
 expect(named('Disintegrating').lifecycle).toBe('disintegrating');
 expect(named('Remnants').visitPoints).toBe(0);
 expect(named('Withering').status).toBe('withering');
 expect(named('Clearing').status).toBe('clearing');
 expect(named('Cracks forming').crossings).toBeGreaterThan(0);
 expect(a.outbreaks.filter(o=>o.lifecycle==='stabilizing')).toHaveLength(2);
 expect(named('On cooldown').eligibleAt).toBeGreaterThan(a.serverTime);
 expect(a.renderTest!.examples.find(e=>e.visited)?.ids).toEqual([named('Visited this outing').id]);
 expect(a.renderTest!.clock).toEqual({paused:true,elapsedMinutes:0,limitMinutes:720});
 const advanced=await renderShowcase(1800000000000,720);
 expect(advanced.renderTest!.clock).toEqual({paused:true,elapsedMinutes:720,limitMinutes:720});
 expect(advanced.serverTime-a.serverTime).toBe(720*60000);
 expect(advanced.outbreaks.find(o=>o.name==='Withering')!.status).not.toBe('withering');
 const {map}=await loadTampereAccess();let timestamp=1;
 const fixes=map.ways.filter(publicAccess).flatMap((way,segment)=>way.geometry.map(p=>({longitude:p.lon,latitude:p.lat,timestamp:timestamp++*1000,segment})));
 const contacts=matchContacts(fixes,a.outbreaks.map(o=>({id:o.id,ring:o.ring,validFrom:0,validUntil:null})),0);
 expect(new Set(contacts.map(c=>c.outbreakId))).toEqual(new Set(a.outbreaks.map(o=>o.id)));
});
